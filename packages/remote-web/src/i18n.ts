export function createLanguage(languages: readonly string[] = navigator.languages) {
  const dictionary = languages.some((language) => language.toLowerCase().startsWith("zh")) ? zh : {}
  return {
    locale: dictionary === zh ? "zh-CN" : "en",
    t(key: Key) {
      return dictionary[key] ?? en[key]
    },
  }
}
